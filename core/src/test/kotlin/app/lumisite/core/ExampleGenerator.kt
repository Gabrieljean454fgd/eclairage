/**
 * Writes a SYNTHETIC example export (no real device involved) to args[0].
 * Run with: ./gradlew :core:generateExample
 */
fun main(args: Array<String>) {
    val out = File(args.firstOrNull() ?: "docs/example/session-example")
    out.deleteRecursively()
    val dir = Files.createTempDirectory("lumi-example").toFile()
    val t0 = 5_000_000_000L
    SessionJournal(dir, Fixtures.header.copy(name = "Exemple synthétique")).use { j ->
        j.event(SessionStarted("evt-start", Fixtures.stamp(t0), "SYNTHETIC example generated by ExampleGenerator.kt"))
        j.gpsStatus(GpsStatusSample(Fixtures.stamp(t0), "gps", "ENABLED_NO_FIX", "indoor, no fix yet (synthetic)"))
        j.event(TrackingStateChanged("evt-trk-init", Fixtures.stamp(t0 + 50_000_000), TrackingState.INITIALIZING))
        j.event(TrackingStateChanged("evt-trk-ok", Fixtures.stamp(t0 + 900_000_000), TrackingState.TRACKING))
        // Walk 12 m "north" in AR frame with slow lateral drift, 10 Hz.
        val poses = (0..120).map { i ->
            val s = i * 0.1
            val st = if (i in 70..74) TrackingState.DEGRADED else TrackingState.TRACKING
            Fixtures.pose(t0 + 1_000_000_000L + i * 100_000_000L, 0.02 * s + 0.05 * sin(s), s, yaw = 0.0, state = st)
        }
        poses.forEachIndexed { i, p ->
            j.pose(p)
            if (i % 10 == 0) {
                j.imu(ImuSample(p.t.copy(sensorNs = p.t.monotonicNs - 1_200_000), 1, "accelerometer (synthetic)", listOf(0.02f, 9.81f, -0.11f), 3))
                j.imu(ImuSample(p.t.copy(sensorNs = p.t.monotonicNs - 1_100_000), 4, "gyroscope (synthetic)", listOf(0.001f, -0.002f, 0.0005f), 3))
            }
        }
        j.event(TrackingStateChanged("evt-trk-deg", poses[70].t, TrackingState.DEGRADED, "INSUFFICIENT_FEATURES"))
        j.event(TrackingStateChanged("evt-trk-ok2", poses[75].t, TrackingState.TRACKING))
        val cal = Calibrator.onePointHeading(
            "evt-cal-1", poses[0].t,
            LocalObservation(poses[0], ReferencePoint("Entrée", Enu(3.0, 2.0), Fixtures.origin, "MAP_TAP", 1.0)),
            cameraHeadingDeg = 15.0, headingSource = "MANUAL", headingUncertaintyDeg = 5.0,
        )
        j.event(cal)
        j.event(SyncEvent("evt-sync-1", poses[5].t, "S1", SyncMethod.MANUAL_TAP, SyncRole.PARTICIPANT, poses[5].t.monotonicNs, notes = "synthetic"))
        listOf(30 to "Applique murale", 60 to "Projecteur encastré", 100 to "Luminaire de sortie").forEachIndexed { k, (i, note) ->
            j.event(SurveyEvent(
                "evt-survey-${k + 1}", poses[i].t, "LUMINAIRE", note, poses[i], poses[i].tracking,
                positionSource = "AR_POSE",
                dxf = DxfHint("ECL_LUMINAIRES", "LUM_GENERIC", attributes = mapOf("NOTE" to note)),
            ))
        }
        j.gps(GpsFix(poses[110].t, "gps", 48.85668, 2.35231, 18f, 52.0, 9f, 0.4f, 12f, poses[110].t.utcEpochMs - 300, 5, 11))
        j.event(Relocalizer.relocalize(
            "evt-reloc-1", poses[115].t, poses[115],
            ReferencePoint("Porte nord", Enu(6.4, 13.3), null, "MAP_TAP", 0.5), cal.transform, notes = "écart constaté à la porte (synthetic)",
        ))
        j.event(SessionStopped("evt-stop", Fixtures.stamp(t0 + 14_000_000_000L), "USER"))
    }
    val site = Fixtures.site.copy(name = "Exemple synthétique", notes = "SYNTHETIC example: values are invented, not measured")
    SessionExporter.exportToDir(site, dir, out, Fixtures.timeBase.referenceUtcEpochMs + 20_000, "lumisite core ExampleGenerator (synthetic)")
    val loaded = SessionImporter.load(out)
    check(loaded.problems.isEmpty()) { loaded.problems.toString() }
    println("Example written to ${out.absolutePath}: ${loaded.poses.size} poses, ${loaded.trajectory.size} corrected points, ${loaded.surveyPoints.size} survey points")
}
